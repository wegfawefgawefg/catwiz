# the songs to game/sound/song_data.tsp: tools/music/songs.tsp is written with
# lib/mockingboard_song's tune.song, which makes a let in main memory; the game keeps its songs
# in aux memory and copies the one playing into main (game/sound/sound.tsp). So this runs
# `tisple expand` on songs.tsp, takes each song's bytes as the library made them, and writes
# them out again with :in aux, with each song's size and the largest.
#
# run: python3 tools/music/export.py   (after changing tools/music/songs.tsp)

import os
import re
import subprocess
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
TISPLE = os.environ.get("TISPLE", os.path.expanduser("~/Coding/LangDev/tisple/build/tisple"))
SOURCE = os.path.join(ROOT, "tools", "music", "songs.tsp")
OUT = os.path.join(ROOT, "game", "sound", "song_data.tsp")


def main():
    # expand needs a main; songs.tsp has none, so expand a copy with one
    work = os.path.join(ROOT, "build", "music")
    os.makedirs(work, exist_ok=True)
    copy = os.path.join(work, "songs.tsp")
    text = open(SOURCE).read()
    open(copy, "w").write(text + "\n(fn main () void)\n")
    out = subprocess.run([TISPLE, "expand", copy], capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(out.stdout + out.stderr)
    # the songs module comes first in the listing, up to the next module
    module = out.stdout.split("; module mockingboard_song")[0]
    songs = re.findall(r"\(let (\w+) \(array u8 (\d+)\)\s+\(make \(array u8 \d+\)([\d\s]+)\)\)", module)
    if not songs:
        sys.exit("no songs in the expansion of " + SOURCE)
    lines = [
        "; generated by tools/music/export.py from tools/music/songs.tsp: never edit by hand.",
        "; The songs' bytes in aux memory; game/sound/sound.tsp copies one into main to play it.",
        "",
    ]
    most = 0
    for name, size, body in songs:
        size = int(size)
        most = max(most, size)
        values = body.split()
        lines.append("(const %s_BYTES u16 %d)" % (name.upper(), size))
        lines.append("(let %s (array u8 %d)" % (name, size))
        lines.append("    (make (array u8 %d)" % size)
        for i in range(0, len(values), 24):
            lines.append("        " + " ".join(values[i:i + 24]))
        lines[-1] += ")"
        lines.append("    :in aux)")
        lines.append("")
        print("%s: %d bytes" % (name, size))
    lines.append("(const MOST_BYTES u16 %d) ; the largest song: the size of the copy in main" % most)
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote %s (the largest %d bytes)" % (OUT, most))


main()
