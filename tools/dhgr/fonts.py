def glyph40(ch):
    # 8 rows of 5 on/off half-pixels
    g = F40.get(ch, F40["?"])
    rows = [(r + ".....")[:5] for r in g] + ["....."] * (8 - len(g))
    return [[b == "#" for b in r] for r in rows[:8]]


def cell_dots(ch, inverse=False):
    # a character's 8 rows of 14 dots (on = white)
    g = glyph40(ch)
    out = []
    for row in g:
        dots = [False] * 14
        for i, on in enumerate(row):
            dots[2 + i * 2] = dots[3 + i * 2] = on
        out.append([d != inverse for d in dots])
    return out


def cell_bytes(ch, inverse=False):
    # the game's table: 8 rows of (aux byte, main byte)
    out = []
    for dots in cell_dots(ch, inverse):
        aux = sum(dots[i] << i for i in range(7))
        main = sum(dots[7 + i] << i for i in range(7))
        out.append((aux, main))
    return out


def text40(lines, row0, s, inverse=()):
    # one 40-column line into `lines` (a dict of screen row -> 560 dot bits) at text row
    # row0 (0-23); inverse: (from, to) column spans in black on white
    for r in range(8):
        lines.setdefault(row0 * 8 + r, [0] * 560)
    for i, ch in enumerate(s.ljust(40)[:40]):
        inv = any(a <= i < b for a, b in inverse)
        for r, dots in enumerate(cell_dots(ch, inv)):
            for k, on in enumerate(dots):
                lines[row0 * 8 + r][i * 14 + k] = 1 if on else 0
    return lines
