def text3(c, x, y, s, col, gap=1, tall=1):
    # tall 2 doubles every row (a 3 x 10 glyph)
    for ch in s:
        g = FONT3.get(ch, FONT3[" "])
        for j, row in enumerate(g):
            for i, b in enumerate(row):
                if b == "#":
                    c.rect(x + i, y + j * tall, x + i + 1, y + (j + 1) * tall, col)
        x += 3 + gap
    return x


def text3_w(s, gap=1):
    return len(s) * (3 + gap) - gap


