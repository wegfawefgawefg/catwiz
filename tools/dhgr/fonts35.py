# the 35-column text font's candidates: each is a whole font, 95 glyphs of 3 colour pixels by 8
# rows, so any of them makes the same 760-byte table (game/art/hud_data FONT35) and swapping one
# in costs no memory. A glyph is a list of rows from the top, "#" a pixel, missing rows blank.
#
# A colour pixel is twice as wide as a row is tall, so a 3-pixel glyph looks 6 wide: fonts drawn
# for square pixels (3 x 5 ones) come out squat here, and the taller candidates make up for it.
# Row 7 blank in every glyph keeps a blank row between lines (in "now" the tails of g, j, p, q, y
# reach row 7 and touch the line below).
#
#     PICK below is the game's font; CATWIZ_FONT=name python3 tools/dhgr/make.py game tries
#     another; python3 tools/dhgr/fonts35.py OUT.png draws every candidate on one sheet.

