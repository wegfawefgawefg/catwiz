RGB = {"white": (255, 255, 255), "lblue": (150, 170, 255), "pink": (255, 120, 230),
       "green": (60, 220, 60), "yellow": (255, 240, 80)}


def sheet(out, now):
    # every candidate's sample lines at the game's pixel shape (a pixel 4 dots by 2 lines), 2x
    from PIL import Image, ImageDraw

    fonts = candidates(now)
    rows = 8 * len(SAMPLE)
    block = rows * 2 + 22
    im = Image.new("RGB", (560, block * len(fonts)), (0, 0, 0))
    d = ImageDraw.Draw(im)
    for f, (name, font) in enumerate(fonts.items()):
        y0 = f * block
        d.text((4, y0 + 4), name + (" (the game's now)" if name == PICK else ""), fill=(255, 240, 80))
        for li, runs in enumerate(SAMPLE):
            col = 0
            for s, c in runs:
                for ch in s:
                    for j, row in enumerate(font.get(ch, font["?"])):
                        for k, b in enumerate(row):
                            if b == "#":
                                x = col * 16 + k * 4
                                y = y0 + 20 + (li * 8 + j) * 2
                                d.rectangle([x, y, x + 3, y + 1], fill=RGB[c])
                    col += 1
    im.resize((1120, im.height * 2), Image.NEAREST).save(out)


