# the double hi-res art as the game's Tisple tables, written to game/art/ (generated: never edit
# by hand). run: python3 tools/dhgr/game.py   (python3 tools/dhgr/make.py game does the same)
#
#   sprites.tsp      every sprite's box and where its runs are; the kinds and their frames
#   runs_KIND.tsp    a kind's runs, packed while compiling: KIND_aux, KIND_main (both in aux
#                    memory; the game unpacks the aux halves to aux memory and the main halves
#                    to the aux language card when a fight starts)
#   NAME_aux.tsp, NAME_main.tsp   a whole screen's halves (8 KB each, $2000-relative), packed:
#                    the fights' backdrops with their shadows, the title
#   hud_data.tsp     the tray's card shapes, the hud font and its icons, the 35-column font
#   icons.tsp        the twelve card pictures as pixels
#   font40.tsp       the 40-column font, for when the text is switched to it
#
# Fighters are lit for the zone of the fights in the build (day, this round): light.py's
# palette swap and rims, offline.

import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import dhgr  # noqa: E402
import forest  # noqa: E402
import game_hud  # noqa: E402
import game_sprites as gs  # noqa: E402
import palettes  # noqa: E402
import screen  # noqa: E402
import title  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "game", "art")
HEAD = "; generated by tools/dhgr/game.py from tools/dhgr/*.py: do not edit, run it again\n"
ZONE = "day"
FIGHTS = palettes.FIGHTS[:2]      # the two fights in the build


def numbers(vals, per=24, indent="        "):
    vals = list(vals)
    return "\n".join(indent + " ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))


def table(name, typ, vals, note=""):
    vals = list(vals)
    head = "(const %s (array %s %d)%s\n    (make (array %s %d)\n" % (name, typ, len(vals), "", typ, len(vals))
    return ("; %s\n" % note if note else "") + head + numbers(vals) + "))\n"


def write(name, text):
    path = os.path.join(OUT, name)
    with open(path, "w") as f:
        f.write(text)
    return path


def packed(name, data, note):
    return "; %s: %d bytes\n(tables.packed_bytes %s (\n%s) :in aux)\n" % (note, len(data), name, numbers(data))


# ---- sprites

def all_sprites():
    # [(kind, [Sprite...], {role: index})], the kinds in KINDS order, then the title's glow
    out = []
    for kind in gs.KINDS:
        if kind == "misc":
            out.append((kind, gs.misc(), {}))
            continue
        sprites = [gs.fighter(kind, f, ZONE) for f in gs.frames(kind)]
        names = gs.frames(kind)
        roles = {}
        for role, frame in gs.ROLES[kind]:
            roles[role] = names.index(frame) if frame else None
        out.append((kind, sprites, roles))
    glow = []
    for i, c in enumerate(title.rims()):
        glow.append(gs.Sprite("glow%d" % i, c))
    out.append(("glow", glow, {}))
    return out


def sprites_module(kinds):
    lines = [HEAD, "; %d kinds, the sprites' boxes in byte columns and rows; DCOL and DTOP from the kind's\n"
             "; idle frame (its first), AUX_AT and MAIN_AT the runs' offsets in the kind's blocks\n" % len(kinds)]
    ids = []
    for k, (kind, sprites, roles) in enumerate(kinds):
        lines.append("(const KIND_%s u8 %d)" % (kind.upper(), k))
    lines.append("(const KIND_COUNT u8 %d)" % len(kinds))
    lines.append("(const NONE u8 255) ; no sprite")
    lines.append("")
    n = 0
    for k, (kind, sprites, roles) in enumerate(kinds):
        for s in sprites:
            lines.append("(const %s u8 %d) ; %d x %d" % (s.name.upper(), n, s.cols, s.rows))
            ids.append((k, kind, s))
            n += 1
    lines.append("(const SPRITE_COUNT u8 %d)" % n)
    lines.append("")
    cols, rows, dcol, dtop, aux_at, main_at, kind_of = [], [], [], [], [], [], []
    for k, (kind, sprites, roles) in enumerate(kinds):
        a = m = 0
        base = sprites[0]
        for s in sprites:
            cols.append(s.cols)
            rows.append(s.rows)
            same = kind in ("misc", "glow")
            dcol.append(0 if same else s.col - base.col)
            dtop.append(0 if same else s.top - base.top)
            aux_at.append(a)
            main_at.append(m)
            kind_of.append(k)
            a += len(s.aux)
            m += len(s.main)
    lines.append(table("COLS", "u8", cols))
    lines.append(table("ROWS", "u8", rows))
    lines.append(table("DCOL", "i8", dcol))
    lines.append(table("DTOP", "i8", dtop))
    lines.append(table("AUX_AT", "u16", aux_at))
    lines.append(table("MAIN_AT", "u16", main_at))
    lines.append(table("KIND_OF", "u8", kind_of))
    # the kinds: where the art stands them (byte column, top row, feet row, width), their runs'
    # sizes, and per role (gs.ROLE_NAMES) the sprite that answers, NONE for the idle frame
    first = {}
    n = 0
    for k, (kind, sprites, roles) in enumerate(kinds):
        first[kind] = n
        n += len(sprites)
    home, top, feet, kcols, asz, msz, frames = [], [], [], [], [], [], []
    for k, (kind, sprites, roles) in enumerate(kinds):
        base = sprites[0]
        home.append(base.col)
        top.append(base.top)
        feet.append(base.top + base.rows)
        kcols.append(base.cols)
        asz.append(sum(len(s.aux) for s in sprites))
        msz.append(sum(len(s.main) for s in sprites))
        for r in gs.ROLE_NAMES:
            i = roles.get(r)
            frames.append(255 if i is None else first[kind] + i)
    lines.append("(const ROLE_COUNT u8 %d) ; %s" % (len(gs.ROLE_NAMES), " ".join(gs.ROLE_NAMES)))
    lines.append(table("KIND_COL", "u8", home))
    lines.append(table("KIND_TOP", "u8", top))
    lines.append(table("KIND_FEET", "u8", feet))
    lines.append(table("KIND_COLS", "u8", kcols))
    lines.append(table("KIND_AUX_SIZE", "u16", asz))
    lines.append(table("KIND_MAIN_SIZE", "u16", msz))
    lines.append(table("KIND_FRAME", "u8", frames, "kind * ROLE_COUNT + role"))
    return "\n".join(lines)


def runs_module(kind, sprites):
    aux = b"".join(s.aux for s in sprites)
    main = b"".join(s.main for s in sprites)
    text = HEAD + "; %s: %d sprites, runs for aux memory (aux) and the aux language card (main)\n\n" % (kind, len(sprites))
    text += "(import tables)\n\n"
    text += packed("%s_aux" % kind, aux, "the aux halves") + "\n"
    text += packed("%s_main" % kind, main, "the main halves")
    return text, len(aux), len(main)


# ---- screens

def fight_picture(F):
    # the backdrop with the fighters' shadows where the art stands them (screen.build's)
    P = F["P"]
    c = forest.picture(P, F["variant"])
    for k in ["cat"] + F["foes"]:
        x0, y0, x1, y1 = screen.figure(k).bbox()
        if k == "nightflap":
            c.ellipse((x0 + x1) / 2, 106, 6, 2.2, P["shadow"])
        else:
            c.ellipse((x0 + x1) / 2 + 1, y1 - 1, (x1 - x0) * 0.36, 2.2, P["shadow"])
    return c


def screen_modules(name, px):
    main, aux = dhgr.to_pages(px)
    out = []
    for half, data in (("aux", aux), ("main", main)):
        text = HEAD + "; %s, the %s memory half of the screen ($2000-relative)\n\n(import tables)\n\n" % (name, half)
        text += packed("picture", data, "the half")
        out.append(("%s_%s.tsp" % (name, half), text))
    return out


# ---- the hud

def hud_module():
    H = game_hud
    lines = [HEAD, "; the tray's cards and the hud's fonts (tools/dhgr/game_hud.py)\n"]
    lines.append("(const TRAY_TOP u8 %d)" % H.TRAY_TOP)
    lines.append("(const TRAY_ROWS u8 %d)" % (H.TRAY_BOTTOM - H.TRAY_TOP))
    lines.append("(const SLOTS u8 %d)" % len(H.CARD_CX))
    first, last = [], []
    for s in range(len(H.CARD_CX)):
        for a, b in H.card_spans(s):
            first.append(a)
            last.append(b)
    lines.append(table("CARD_FIRST", "u8", first, "slot * TRAY_ROWS + row: the white of the tilted card, pixels"))
    lines.append(table("CARD_END", "u8", last))
    rects = []
    for s in range(len(H.CARD_CX)):
        for x0, x1, y0, y1, col in H.picked_rects(s):
            rects += [x0, x1, y0, y1, col]
    lines.append(table("PICKED", "u8", rects, "slot * 15: the picked card's rim, edge and white, each x0 x1 y0 y1 colour"))
    ix, iy, px_, py_ = [], [], [], []
    for s in range(len(H.CARD_CX)):
        x, y = H.icon_at(s, False)
        ix.append(x)
        iy.append(y)
        x, y = H.icon_at(s, True)
        px_.append(x)
        py_.append(y)
    lines.append(table("ICON_X", "u8", ix, "where each slot's picture goes, and picked"))
    lines.append(table("ICON_Y", "u8", iy))
    lines.append(table("PICKED_ICON_X", "u8", px_))
    lines.append(table("PICKED_ICON_Y", "u8", py_))
    lines.append(table("CARD_X", "u8", [int(round(x)) for x in H.CARD_CX], "the cards' middles"))
    g0s, gns = [], []
    for s_ in range(len(H.CARD_CX)):
        xs = [a for a, b in H.card_spans(s_) if b > a] + [r[0] for r in H.picked_rects(s_)]
        xe = [b for a, b in H.card_spans(s_) if b > a] + [r[1] for r in H.picked_rects(s_)]
        g0 = min(xs) // 7
        g0s.append(g0)
        gns.append((max(xe) + 6) // 7 - g0)
    lines.append(table("SLOT_G0", "u8", g0s, "the 7-pixel groups each slot's card covers, picked or not"))
    lines.append(table("SLOT_GN", "u8", gns))
    lines.append("(const CAPTION_Y u8 %d)\n(const PICKED_CAPTION_Y u8 %d)" % (H.caption_y(False), H.caption_y(True)))
    lines.append(table("HUD_FONT", "u8", H.hud_font(), "from ' ' to '_': width, colour (0: the ink's), 6 rows of bits"))
    lines.append(table("FONT35", "u8", H.font35(), "95 glyphs from ' ': 8 rows of 3 pixels, a byte a row, bit 0 the leftmost"))
    return "\n".join(lines)


def icons_module():
    H = game_hud
    data = b"".join(H.icon_pixels(n) for n in H.ICON_ORDER)
    text = HEAD + "; the card pictures in content/faces' TILE order, 15 rows of 11 pixels as nibbles (6 bytes a\n; row): %s\n\n" % " ".join(H.ICON_ORDER)
    text += "(const ICON_BYTES u16 90)\n"
    for i, n in enumerate(H.ICON_ORDER):
        text += "(const TILE_%s u8 %d)\n" % (n.upper(), i)
    text += "(const PIXELS (array u8 %d) (make (array u8 %d)\n%s))\n" % (len(data), len(data), numbers(data))
    return text


def font40_module():
    data = game_hud.font40()
    return HEAD + "; the 40-column font: 95 glyphs from ' ', 8 rows of (aux, main) bytes\n\n" + table("FONT40", "u8", data)


def main():
    os.makedirs(OUT, exist_ok=True)
    kinds = all_sprites()
    print(write("sprites.tsp", sprites_module(kinds)))
    for kind, sprites, _ in kinds:
        text, na, nm = runs_module(kind, sprites)
        print(write("runs_%s.tsp" % kind, text), na, nm)
    for F in FIGHTS:
        for name, text in screen_modules("fight%d" % F["n"], fight_picture(F).px):
            print(write(name, text))
    for name, text in screen_modules("title", title.picture().px):
        print(write(name, text))
    print(write("hud_data.tsp", hud_module()))
    print(write("icons.tsp", icons_module()))
    print(write("font40.tsp", font40_module()))


if __name__ == "__main__":
    main()
