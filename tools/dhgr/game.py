# the double hi-res art as the game's Tisple tables, written to game/art/ (generated: never edit
# by hand). run: python3 tools/dhgr/game.py   (python3 tools/dhgr/make.py game does the same)
#
#   sprites.tsp      the sprites' numbers the code names (the hero's and the small sprites',
#                    the same on every fight screen; the title's glow), the figures' numbers
#                    (FIG_: an enemy's figure, content/enemies.tsp), and the screen's tables
#                    (tab): every sprite's box, where its runs are and its block (KIND_OF), its
#                    SOLID (1: only opaque runs over its whole box, the figure on black; 0
#                    masked: the marker, bolt, poofs, digits, shots, the glow); each kind's
#                    place (col, top, feet, cols, reach, left) and the sprite for each role
#                    (frame: kind * ROLE_COUNT + role, NONE for the idle frame); each block's
#                    runs' sizes; and each figure's kind on this screen (figure, NONE when it
#                    is not here). Read from the disk with a screen's runs: in main memory,
#                    the size of the largest screen's
#   hero.tsp         the hero's and the small sprites' runs (blocks 0 and 1 of every fight
#                    screen), on the second disk: read once, kept while fights follow
#   screen_fightN.tsp  fight row N - 1's screen on the second disk (draw/packs: packed while
#                    compiling): PICTURE, its two halves (8 KB each, $2000-relative); RUNS, the
#                    screen's tables, then its enemies' blocks' runs, every main half (to the
#                    aux language card), then every aux half (to aux memory)
#   screen_title.tsp the title: PICTURE and RUNS (its tables, the glow) on the boot disk, and
#                    PICTURE2 and RUNS2, the same on the second disk for the titles after a run
#                    (a machine with one drive has the second disk in then)
#   hud_data.tsp     the tray's card shapes, the hud font and its icons, the 35-column font
#   icons.tsp        the cards memory keeps (nap, bonus, door, grabbed) as pixels and their TILEs
#   pictures.tsp     every face's and charm's picture by name, for the catalog on disk 2
#   font40.tsp       the 40-column font, for when the text is switched to it
#
# Fighters are lit for the zone of the fights in the build (night: the whole game is midnight
# since 2026-10-31): light.py's palette swap and rims, offline. The fight backdrops are black
# in every lane (lanes.py); the scenery is night.py's.

