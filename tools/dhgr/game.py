# the double hi-res art as the game's Tisple tables, written to game/art/ (generated: never edit
# by hand). run: python3 tools/dhgr/game.py   (python3 tools/dhgr/make.py game does the same)
#
#   sprites.tsp      every sprite's box and where its runs are; the kinds and their frames.
#                    SOLID: 1 for a solid frame (every fighter frame and flash: each row only
#                    opaque runs over the whole box, the figure on black), 0 for a masked one
#                    (the marker, bolt, poofs, digits, the title's glow). KIND_FRAME by role:
#                    idle attack hurt happy surprised flap flash (ROLE_COUNT 7); flash is the
#                    white silhouette of the hurt frame, in its box, for the hit flash
#   screen_NAME.tsp  a screen's art on the disk (draw/packs: packed while compiling, read
#                    whole when the screen starts): PICTURE, its two halves (8 KB each,
#                    $2000-relative); RUNS, the runs of its kinds (KINDS), every main half (to the
#                    aux language card), then every aux half (to aux memory). screen_fight1 (the
#                    clearing), screen_fight2 (the path), screen_title
#   hud_data.tsp     the tray's card shapes, the hud font and its icons, the 35-column font
#   icons.tsp        the card pictures as pixels (in aux memory) and their TILE numbers
#   font40.tsp       the 40-column font, for when the text is switched to it
#
# Fighters are lit for the zone of the fights in the build (night: the whole game is midnight
# since 2026-10-31): light.py's palette swap and rims, offline. The fight backdrops are black
# in every lane (lanes.py); the scenery is night.py's.

import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import dhgr  # noqa: E402
import game_hud  # noqa: E402
import game_sprites as gs  # noqa: E402
import night  # noqa: E402
import palettes  # noqa: E402
import title  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "game", "art")
HEAD = "; generated by tools/dhgr/game.py from tools/dhgr/*.py: do not edit, run it again\n"
ZONE = "night"
FIGHTS = palettes.FIGHTS[:2]      # the two fights in the build


def numbers(vals, per=24, indent="        "):
    vals = list(vals)
    return "\n".join(indent + " ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))


def table(name, typ, vals, note=""):
    vals = list(vals)
    head = "(const %s (array %s %d)%s\n    (make (array %s %d)\n" % (name, typ, len(vals), "", typ, len(vals))
    return ("; %s\n" % note if note else "") + head + numbers(vals) + "))\n"


def write(name, text):
    path = os.path.join(OUT, name)
    with open(path, "w") as f:
        f.write(text)
    return path


# ---- sprites

def all_sprites():
    # [(kind, [Sprite...], {role: index})], the kinds in KINDS order, then the title's glow
    out = []
    for kind in gs.KINDS:
        if kind == "misc":
            out.append((kind, gs.misc(), {}))
            continue
        sprites = [gs.fighter(kind, f, ZONE) for f in gs.frames(kind)] + [gs.flash(kind)]
        names = gs.frames(kind) + ["flash"]
        roles = {}
        for role, frame in gs.ROLES[kind]:
            roles[role] = names.index(frame) if frame else None
        out.append((kind, sprites, roles))
    glow = []
    for i, c in enumerate(title.rims()):
        glow.append(gs.Sprite("glow%d" % i, c))
    out.append(("glow", glow, {}))
    return out


def sprites_module(kinds):
    lines = [HEAD, "; %d kinds, the sprites' boxes in byte columns and rows; DCOL and DTOP from the kind's\n"
             "; idle frame (its first), AUX_AT and MAIN_AT the runs' offsets in the kind's blocks\n" % len(kinds)]
    ids = []
    for k, (kind, sprites, roles) in enumerate(kinds):
        lines.append("(const KIND_%s u8 %d)" % (kind.upper(), k))
    lines.append("(const KIND_COUNT u8 %d)" % len(kinds))
    lines.append("(const NONE u8 255) ; no sprite")
    lines.append("")
    n = 0
    for k, (kind, sprites, roles) in enumerate(kinds):
        for s in sprites:
            lines.append("(const %s u8 %d) ; %d x %d" % (s.name.upper(), n, s.cols, s.rows))
            ids.append((k, kind, s))
            n += 1
    lines.append("(const SPRITE_COUNT u8 %d)" % n)
    lines.append("")
    cols, rows, dcol, dtop, aux_at, main_at, kind_of, solid = [], [], [], [], [], [], [], []
    for k, (kind, sprites, roles) in enumerate(kinds):
        a = m = 0
        base = sprites[0]
        for s in sprites:
            cols.append(s.cols)
            rows.append(s.rows)
            same = kind in ("misc", "glow")
            dcol.append(0 if same else s.col - base.col)
            dtop.append(0 if same else s.top - base.top)
            aux_at.append(a)
            main_at.append(m)
            kind_of.append(k)
            solid.append(1 if s.solid else 0)
            a += len(s.aux)
            m += len(s.main)
    lines.append(table("COLS", "u8", cols))
    lines.append(table("ROWS", "u8", rows))
    lines.append(table("DCOL", "i8", dcol))
    lines.append(table("DTOP", "i8", dtop))
    lines.append(table("AUX_AT", "u16", aux_at))
    lines.append(table("MAIN_AT", "u16", main_at))
    lines.append(table("KIND_OF", "u8", kind_of))
    lines.append(table("SOLID", "u8", solid, "1: a solid frame (only opaque runs over its whole box, the figure on black); 0: masked"))
    # the kinds: where the art stands them (byte column, top row, feet row, width), their runs'
    # sizes, and per role (gs.ROLE_NAMES) the sprite that answers, NONE for the idle frame
    first = {}
    n = 0
    for k, (kind, sprites, roles) in enumerate(kinds):
        first[kind] = n
        n += len(sprites)
    home, top, feet, kcols, asz, msz, frames, reach, left = [], [], [], [], [], [], [], [], []
    for k, (kind, sprites, roles) in enumerate(kinds):
        base = sprites[0]
        home.append(base.col)
        top.append(base.top)
        feet.append(base.top + base.rows)
        kcols.append(base.cols)
        reach.append(max(sp.col + sp.cols for sp in sprites) - base.col)
        left.append(base.col - min(sp.col for sp in sprites))
        asz.append(sum(len(s.aux) for s in sprites))
        msz.append(sum(len(s.main) for s in sprites))
        for r in gs.ROLE_NAMES:
            i = roles.get(r)
            frames.append(255 if i is None else first[kind] + i)
    lines.append("(const ROLE_COUNT u8 %d) ; %s" % (len(gs.ROLE_NAMES), " ".join(gs.ROLE_NAMES)))
    lines.append(table("KIND_COL", "u8", home))
    lines.append(table("KIND_TOP", "u8", top))
    lines.append(table("KIND_FEET", "u8", feet))
    lines.append(table("KIND_COLS", "u8", kcols))
    lines.append(table("KIND_REACH", "u8", reach, "how far right of its home column any frame reaches, and left"))
    lines.append(table("KIND_LEFT", "u8", left))
    lines.append(table("KIND_AUX_SIZE", "u16", asz))
    lines.append(table("KIND_MAIN_SIZE", "u16", msz))
    lines.append(table("KIND_FRAME", "u8", frames, "kind * ROLE_COUNT + role"))
    return "\n".join(lines)


def runs_halves(sprites):
    # a kind's runs: its aux halves and its main halves, sprite after sprite
    return b"".join(s.aux for s in sprites), b"".join(s.main for s in sprites)


# ---- screens

def fight_picture(F):
    # the backdrop: the fight's night, black in every lane (night.py, lanes.py); no shadows,
    # since every spot under a fighter is in a lane
    return night.picture(F["variant"])


def screen_module(name, px, kinds, ids):
    # PICTURE: the screen's aux half, then its main half (8 KB each, $2000-relative); RUNS: its
    # kinds' runs, every main half in KINDS order, then every aux half (blit.unpack_all's
    # order). Both draw/packs tables: read whole, unpacked part by part
    main, aux = dhgr.to_pages(px)
    text = HEAD + "; %s: the picture and the runs of its kinds (%s), packed, on the disk\n\n" % (
        name, " ".join(k for k, _ in kinds))
    text += "(import draw/packs)\n\n"
    text += table("KINDS", "u8", ids, "the kinds' numbers (art/sprites KIND_), the runs' order")
    text += "\n; the picture: its aux half, its main half\n(packs.packs PICTURE\n    (\n%s)\n    (\n%s))\n" % (
        numbers(aux), numbers(main))
    halves = [runs_halves(sprites) for _, sprites in kinds]
    text += "\n; the runs: every main half, then every aux half\n(packs.packs RUNS\n"
    text += "\n".join("    (\n%s)" % numbers(m) for _, m in halves) + "\n"
    text += "\n".join("    (\n%s)" % numbers(a) for a, _ in halves) + ")\n"
    return text


# ---- the hud

def hud_module():
    H = game_hud
    lines = [HEAD, "; the tray's cards and the hud's fonts (tools/dhgr/game_hud.py)\n"]
    lines.append("(const TRAY_TOP u8 %d)" % H.TRAY_TOP)
    lines.append("(const TRAY_ROWS u8 %d)" % (H.TRAY_BOTTOM - H.TRAY_TOP))
    lines.append("(const SLOTS u8 %d)" % len(H.CARD_CX))
    first, last = [], []
    for s in range(len(H.CARD_CX)):
        for a, b in H.card_spans(s):
            first.append(a)
            last.append(b)
    lines.append(table("CARD_FIRST", "u8", first, "slot * TRAY_ROWS + row: the white of the tilted card, pixels"))
    lines.append(table("CARD_END", "u8", last))
    ix, iy = [], []
    for s in range(len(H.CARD_CX)):
        x, y = H.icon_at(s)
        ix.append(x)
        iy.append(y)
    lines.append(table("ICON_X", "u8", ix, "where each slot's picture goes"))
    lines.append(table("ICON_Y", "u8", iy))
    lines.append(table("CARD_X", "u8", [int(round(x)) for x in H.CARD_CX], "the cards' middles"))
    g0s, gns = [], []
    for s_ in range(len(H.CARD_CX)):
        xs = [a for a, b in H.card_spans(s_) if b > a]
        xe = [b for a, b in H.card_spans(s_) if b > a]
        g0 = min(xs) // 7
        g0s.append(g0)
        gns.append((max(xe) + 6) // 7 - g0)
    lines.append(table("SLOT_G0", "u8", g0s, "the 7-pixel groups each slot's card covers"))
    lines.append(table("SLOT_GN", "u8", gns))
    top, bottom = H.card_rows()
    lines.append("; each slot is byte columns SLOT_COLS * n on; its card covers rows CARD_TOP to CARD_BOTTOM - 1,\n"
                 "; picked lifted LIFT rows with a glow of GLOW_ROWS rows under it\n"
                 "(const SLOT_COLS u8 %d)\n(const CARD_TOP u8 %d)\n(const CARD_BOTTOM u8 %d)\n"
                 "(const LIFT u8 %d)\n(const GLOW_ROWS u8 %d)" % (H.hud.SLOT_COLS, top, bottom, H.hud.LIFT, H.hud.GLOW_ROWS))
    lines.append("(const CAPTION_Y u8 %d)" % H.caption_y())
    lines.append(table("HUD_FONT", "u8", H.hud_font(), "from ' ' to '_': width, colour (0: the ink's), 6 rows of bits"))
    lines.append(table("FONT35", "u8", H.font35(), "95 glyphs from ' ': 8 rows of 3 pixels, a byte a row, bit 0 the leftmost"))
    return "\n".join(lines)


def icons_module():
    H = game_hud
    data = b"".join(H.icon_pixels(n) for n in H.ICON_ORDER)
    text = HEAD + "; the card pictures, 15 rows of 11 pixels as nibbles (6 bytes a row), in aux memory (the\n; tray and the stage copy one out to draw it): %s\n\n" % " ".join(H.ICON_ORDER)
    text += "(const ICON_BYTES u16 90)\n"
    for i, n in enumerate(H.ICON_ORDER):
        text += "(const TILE_%s u8 %d)\n" % (n.upper(), i)
    text += "(let pixels (array u8 %d) (make (array u8 %d)\n%s) :in aux)\n" % (len(data), len(data), numbers(data))
    return text


def font40_module():
    data = game_hud.font40()
    return HEAD + "; the 40-column font: 95 glyphs from ' ', 8 rows of (aux, main) bytes\n\n" + table("FONT40", "u8", data)


def main():
    os.makedirs(OUT, exist_ok=True)
    kinds = all_sprites()
    print(write("sprites.tsp", sprites_module(kinds)))
    ids = {kind: i for i, (kind, _, _) in enumerate(kinds)}
    sprites = {kind: s for kind, s, _ in kinds}

    def cast(names):
        return [(k, sprites[k]) for k in names], [ids[k] for k in names]

    # the fights' kinds in the order battle.load_art wanted them (the hero, the small sprites,
    # then the enemies' figures): the order they are placed in (tools/dhgr/memory.py)
    for F in FIGHTS:
        names = ["cat", "misc", "puffcap", "sporelet"] + (["nightflap"] if F["n"] == 2 else [])
        ks, ns = cast(names)
        print(write("screen_fight%d.tsp" % F["n"], screen_module("fight %d" % F["n"], fight_picture(F).px, ks, ns)))
    ks, ns = cast(["glow"])
    print(write("screen_title.tsp", screen_module("the title", title.picture().px, ks, ns)))
    print(write("hud_data.tsp", hud_module()))
    print(write("icons.tsp", icons_module()))
    print(write("font40.tsp", font40_module()))


if __name__ == "__main__":
    main()
