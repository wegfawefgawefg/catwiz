ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "game", "art")
HEAD = "; generated by tools/dhgr/game.py from tools/dhgr/*.py: do not edit, run it again\n"
ZONE = "night"
NONE = 255
HERO_BLOCKS = ["cat", "misc"]


def numbers(vals, per=24, indent="        "):
    vals = list(vals)
    return "\n".join(indent + " ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))


def table(name, typ, vals, note="", options=""):
    vals = list(vals)
    head = "(const %s (array %s %d)%s\n    (make (array %s %d)\n" % (name, typ, len(vals), "", typ, len(vals))
    tail = ")\n%s)\n" % options if options else "))\n"
    return ("; %s\n" % note if note else "") + head + numbers(vals) + tail


def write(name, text):
    path = os.path.join(OUT, name)
    with open(path, "w") as f:
        f.write(text)
    return path


# ---- sprites: the blocks' sprites, made once

_SPRITES = {}


def sprites_of(block):
    # a block's sprites (game_sprites), in figures.frame_names order; misc and glow by hand
    if block not in _SPRITES:
        if block == "misc":
            _SPRITES[block] = gs.misc()
        elif block == "glow":
            _SPRITES[block] = [gs.Sprite("glow%d" % i, c) for i, c in enumerate(title.rims())]
        else:
            _SPRITES[block] = gs.block_sprites(block, ZONE)
    return _SPRITES[block]


def names_of(block):
    if block in ("misc", "glow"):
        return [s.name for s in sprites_of(block)]
    return figures.frame_names(figures.BLOCKS[block])


class Screen:
    # one screen's tables: its blocks (runs), kinds (role tables) and their sprites
    def __init__(self, blocks, kinds):
        self.blocks = blocks
        self.kinds = kinds
        self.first = {}
        self.sprites = []
        self.kind_of = []
        for b, name in enumerate(blocks):
            self.first[name] = len(self.sprites)
            for s in sprites_of(name):
                self.sprites.append(s)
                self.kind_of.append(b)

    def sprite(self, block, frame):
        return self.first[block] + names_of(block).index(frame)

    def kind_rows(self, kind):
        # (col, top, feet, cols, reach, left) and the role sprites, for a kind of this screen
        if kind in ("misc", "glow"):
            base = sprites_of(kind)[0]
            return (base.col, base.top, base.top + base.rows, base.cols, 0, 0), [NONE] * len(figures.ROLE_NAMES)
        K = figures.KINDS[kind]
        b = K.block
        base = sprites_of(b)[0]
        frames = []
        role_frames = []
        for r in figures.ROLE_NAMES:
            f = K.roles.get(r)
            if f is None:
                frames.append(NONE)
                continue
            i = self.sprite(b, f)
            frames.append(i)
            if not r.startswith("shot"):
                role_frames.append(self.sprites[i])
        idle = self.sprites[frames[0]]
        reach = max(sp.col + sp.cols for sp in role_frames) - base.col
        left = base.col - min(sp.col for sp in role_frames)
        return (base.col, base.top, base.top + base.rows, base.cols, reach, left), frames


def screen_of(F):
    # the enemies' blocks in the order that fits the sprite room best (blit places them in the
    # table's order, each half whole where it first fits: memory.py)
    import itertools
    import memory
    blocks, kinds = screens.blocks_of(F["kinds"])
    best = None
    for order in itertools.permutations(blocks):
        short = memory.short_of(list(order))
        if best is None or short < best[0]:
            best = (short, list(order))
        if short == 0:
            break
    order = best[1]
    kinds = order + [k for k in kinds if k not in order]
    return Screen(HERO_BLOCKS + order, HERO_BLOCKS + kinds)


def title_screen():
    return Screen(["glow"], ["glow"])


# the tables' sizes: the largest screen's, so one let holds any screen's
def table_sizes(all_screens):
    return (max(len(S.sprites) for S in all_screens), max(len(S.kinds) for S in all_screens),
            max(len(S.blocks) for S in all_screens))


FIELDS_SPRITE = ["cols", "rows", "dcol", "dtop", "aux_lo", "aux_hi", "main_lo", "main_hi", "kind_of", "solid"]
FIELDS_KIND = ["kcol", "ktop", "kfeet", "kcols", "kreach", "kleft"]
FIELDS_BLOCK = ["aux_size_lo", "aux_size_hi", "main_size_lo", "main_size_hi"]


def tables_bytes(S, sizes):
    # the screen's tables as the bytes of art/sprites' Tables, field after field
    most_s, most_k, most_b = sizes
    roles = len(figures.ROLE_NAMES)
    f = {n: [0] * most_s for n in FIELDS_SPRITE}
    at = {}
    for b, name in enumerate(S.blocks):
        a = m = 0
        base = sprites_of(name)[0]
        for s in sprites_of(name):
            i = S.first[name] + sprites_of(name).index(s)
            same = name in ("misc", "glow")
            f["cols"][i] = s.cols
            f["rows"][i] = s.rows
            f["dcol"][i] = (0 if same else s.col - base.col) & 0xFF
            f["dtop"][i] = (0 if same else s.top - base.top) & 0xFF
            f["aux_lo"][i], f["aux_hi"][i] = a & 0xFF, a >> 8
            f["main_lo"][i], f["main_hi"][i] = m & 0xFF, m >> 8
            f["kind_of"][i] = b
            f["solid"][i] = 1 if s.solid else 0
            a += len(s.aux)
            m += len(s.main)
        at[name] = (a, m)
    k = {n: [0] * most_k for n in FIELDS_KIND}
    frame = [NONE] * (most_k * roles)
    for i, kind in enumerate(S.kinds):
        place, frames = S.kind_rows(kind)
        for n, v in zip(FIELDS_KIND, place):
            k[n][i] = v
        frame[i * roles:(i + 1) * roles] = frames
    bl = {n: [0] * most_b for n in FIELDS_BLOCK}
    for i, name in enumerate(S.blocks):
        a, m = at[name]
        bl["aux_size_lo"][i], bl["aux_size_hi"][i] = a & 0xFF, a >> 8
        bl["main_size_lo"][i], bl["main_size_hi"][i] = m & 0xFF, m >> 8
    fig = [NONE] * len(screens.FIGURES)
    for i, kind in enumerate(S.kinds):
        if kind in screens.FIGURES:
            fig[screens.FIGURES.index(kind)] = i
    out = [len(S.blocks)]
    for n in FIELDS_SPRITE:
        out += f[n]
    for n in FIELDS_KIND:
        out += k[n]
    out += frame
    for n in FIELDS_BLOCK:
        out += bl[n]
    return out + fig


def sprites_module(sizes, title_S):
    most_s, most_k, most_b = sizes
    roles = len(figures.ROLE_NAMES)
    lines = [HEAD, "; the sprites' numbers the code names, the figures', and the screen's tables (tab), read\n"
             "; from the disk with each screen's runs (tools/dhgr/game.py: the formats)\n"]
    lines.append("(const KIND_CAT u8 0)\n(const KIND_MISC u8 1)\n(const KIND_GLOW u8 0) ; on the title")
    lines.append("(const NONE u8 255) ; no sprite, no kind")
    lines.append("(const ROLE_COUNT u8 %d) ; %s" % (roles, " ".join(figures.ROLE_NAMES)))
    lines.append("(const SPRITES_MOST u8 %d)\n(const KINDS_MOST u8 %d)\n(const BLOCKS_MOST u8 %d)" % sizes)
    lines.append("")
    n = 0
    for name in HERO_BLOCKS:
        for s in sprites_of(name):
            lines.append("(const %s u8 %d) ; %d x %d" % (s.name.upper(), n, s.cols, s.rows))
            n += 1
    for i, s in enumerate(sprites_of("glow")):
        lines.append("(const %s u8 %d) ; %d x %d, on the title" % (s.name.upper(), i, s.cols, s.rows))
    lines.append("")
    lines.append("; the figures an enemy is drawn as (content/enemies.tsp :figure)")
    for i, name in enumerate(screens.FIGURES):
        lines.append("(const FIG_%s u8 %d)" % (name.upper(), i))
    lines.append("(const FIGURE_COUNT u8 %d)" % len(screens.FIGURES))
    lines.append("")
    fields = ["(blocks u8)"]
    for name in FIELDS_SPRITE:
        typ = "i8" if name in ("dcol", "dtop") else "u8"
        fields.append("(%s (array %s %d))" % (name, typ, most_s))
    for name in FIELDS_KIND:
        fields.append("(%s (array u8 %d))" % (name, most_k))
    fields.append("(frame (array u8 %d))" % (most_k * roles))
    for name in FIELDS_BLOCK:
        fields.append("(%s (array u8 %d))" % (name, most_b))
    fields.append("(figure (array u8 %d))" % len(screens.FIGURES))
    lines.append("; a screen's tables: blocks the number of its blocks (the hero's 0, the small sprites' 1,\n"
                 "; then the enemies'); by sprite its box (byte columns, rows; dcol, dtop from its block's\n"
                 "; first frame), its runs' offsets in its block (lo, hi), its block, SOLID; by kind where\n"
                 "; its idle frame stands, how far right and left any frame reaches, and the sprite for\n"
                 "; each role (kind * ROLE_COUNT + role, NONE for the idle frame); by block its runs' sizes;\n"
                 "; by figure its kind here (NONE: not on this screen)")
    lines.append("(struct Tables (" + "\n        ".join(fields) + "))\n")
    lines.append("(let tab Tables)")
    return "\n".join(lines) + "\n"


def runs_halves(sprites):
    # a block's runs: its aux halves and its main halves, sprite after sprite
    return b"".join(s.aux for s in sprites), b"".join(s.main for s in sprites)


# ---- screens

def fight_picture(F):
    # the backdrop: the fight's night, black in every lane (night.py, lanes.py); no shadows,
    # since every spot under a fighter is in a lane
    return night.picture_for(F)


def packs_text(name, where, parts):
    return "(packs.packs %s %s\n%s)\n" % (name, where, "\n".join("    (\n%s)" % numbers(p) for p in parts))


def picture_parts(px):
    main, aux = dhgr.to_pages(px)
    return [aux, main]


def runs_parts(S, sizes, blocks):
    halves = [runs_halves(sprites_of(b)) for b in blocks]
    return [tables_bytes(S, sizes)] + [m for _, m in halves] + [a for a, _ in halves]


def fight_module(F, S, sizes):
    text = HEAD + "; fight %d's screen (row %d of FIGHTS): the picture, and the runs of its enemies' blocks\n" % (F["n"], F["row"])
    text += "; (%s) after the screen's tables, packed, on the second disk\n\n(import draw/packs)\n\n" % " ".join(S.blocks[2:])
    text += "; the picture: its aux half, its main half\n"
    text += packs_text("PICTURE", "disk2", picture_parts(fight_picture(F).px))
    text += "\n; the tables, then the runs: every main half, then every aux half\n"
    text += packs_text("RUNS", "disk2", runs_parts(S, sizes, S.blocks[2:]))
    return text


def hero_module(sizes):
    S = Screen(HERO_BLOCKS, HERO_BLOCKS)
    text = HEAD + "; the hero's and the small sprites' runs, blocks 0 and 1 of every fight screen, after\n"
    text += "; the tables of a screen of only them: their main halves, then their aux halves, packed,\n"
    text += "; on the second disk\n\n(import draw/packs)\n\n"
    text += packs_text("RUNS", "disk2", runs_parts(S, sizes, HERO_BLOCKS))
    return text


def title_module(S, sizes):
    pic = picture_parts(title.picture().px)
    runs = runs_parts(S, sizes, ["glow"])
    text = HEAD + "; the title: the picture, and its tables and the glow's runs, on the boot disk (PICTURE,\n"
    text += "; RUNS) and the second (PICTURE2, RUNS2)\n\n(import draw/packs)\n\n"
    text += packs_text("PICTURE", "disk", pic) + "\n" + packs_text("RUNS", "disk", runs)
    text += "\n" + packs_text("PICTURE2", "disk2", pic) + "\n" + packs_text("RUNS2", "disk2", runs)
    return text


# ---- the hud

def hud_module():
    H = game_hud
    lines = [HEAD, "; the tray's cards and the hud's fonts (tools/dhgr/game_hud.py)\n"]
    lines.append("(const TRAY_TOP u8 %d)" % H.TRAY_TOP)
    lines.append("(const TRAY_ROWS u8 %d)" % (H.TRAY_BOTTOM - H.TRAY_TOP))
    lines.append("(const SLOTS u8 %d)" % len(H.CARD_CX))
    # the cards' white spans, rows CARD_ROW0 on (the ones any card has), one table a shape:
    # slots whose cards are the same shape moved sideways share one (CARD_SHAPE its first
    # entry, CARD_SHIFT the pixels to add), which keeps main memory's bytes down
    spans = [H.card_spans(s) for s in range(len(H.CARD_CX))]
    used = [r for sp in spans for r, (a, b) in enumerate(sp) if b > a]
    r0, r1 = min(used), max(used) + 1
    shapes, shape_of, shift = [], [], []
    for sp in spans:
        rows = sp[r0:r1]
        x0 = min(a for a, b in rows if b > a)
        rel = [(a - x0, b - x0) if b > a else (0, 0) for a, b in rows]
        if rel not in shapes:
            shapes.append(rel)
        shape_of.append(shapes.index(rel) * (r1 - r0))
        shift.append(x0)
    first = [a for sh in shapes for a, b in sh]
    last = [b for sh in shapes for a, b in sh]
    lines.append("(const CARD_ROW0 u8 %d) ; the first tray row a card covers\n(const CARD_ROWS u8 %d)" % (r0, r1 - r0))
    lines.append(table("CARD_SHAPE", "u8", shape_of, "each slot's card: its shape's first entry in CARD_FIRST and CARD_END, and its pixels' shift"))
    lines.append(table("CARD_SHIFT", "u8", shift))
    lines.append(table("CARD_FIRST", "u8", first, "shape + row - CARD_ROW0: the white of a tilted card, pixels from its leftmost (0, 0 for none)"))
    lines.append(table("CARD_END", "u8", last))
    ix, iy = [], []
    for s in range(len(H.CARD_CX)):
        x, y = H.icon_at(s)
        ix.append(x)
        iy.append(y)
    lines.append(table("ICON_X", "u8", ix, "where each slot's picture goes"))
    lines.append(table("ICON_Y", "u8", iy))
    lines.append(table("CARD_X", "u8", [int(round(x)) for x in H.CARD_CX], "the cards' middles"))
    g0s, gns = [], []
    for s_ in range(len(H.CARD_CX)):
        xs = [a for a, b in H.card_spans(s_) if b > a]
        xe = [b for a, b in H.card_spans(s_) if b > a]
        g0 = min(xs) // 7
        g0s.append(g0)
        gns.append((max(xe) + 6) // 7 - g0)
    lines.append(table("SLOT_G0", "u8", g0s, "the 7-pixel groups each slot's card covers"))
    lines.append(table("SLOT_GN", "u8", gns))
    top, bottom = H.card_rows()
    lines.append("; each slot is byte columns SLOT_COLS * n on; its card covers rows CARD_TOP to CARD_BOTTOM - 1,\n"
                 "; picked lifted LIFT rows with a glow of GLOW_ROWS rows under it\n"
                 "(const SLOT_COLS u8 %d)\n(const CARD_TOP u8 %d)\n(const CARD_BOTTOM u8 %d)\n"
                 "(const LIFT u8 %d)\n(const GLOW_ROWS u8 %d)" % (H.hud.SLOT_COLS, top, bottom, H.hud.LIFT, H.hud.GLOW_ROWS))
    lines.append("(const CAPTION_Y u8 %d)" % H.caption_y())
    lines.append(table("HUD_FONT", "u8", H.hud_font(), "from ' ' to '_': width, colour (0: the ink's), 6 rows of bits"))
    lines.append(table("FONT35", "u8", H.font35(), "95 glyphs from ' ': 8 rows of 3 pixels, a byte a row, bit 0 the leftmost"))
    return "\n".join(lines)


# the pictures the game keeps in memory (art/icons, packed in aux memory): the cards between
# fights that are no face or charm (the nap, the bonus upgrade, a door) and a die an enemy holds.
# Their TILE numbers start at FIRST_TILE, past the rows of faces and charms in play (content/items:
# a row's tile is the row, its picture in its catalog record)
RESIDENT = ["nap", "plus1", "door", "grabbed"]
FIRST_TILE = 32


def icons_module():
    # each picture packed on its own (tables.packed_bytes: ZX0 while compiling), in aux memory,
    # and PICTURES their places: draw/paint unpacks one into main memory to draw it
    H = game_hud
    text = HEAD + "; the card pictures memory keeps, 15 rows of 11 pixels as nibbles (6 bytes a row, ICON_BYTES),\n"
    text += "; each packed in aux memory (draw/paint unpacks one to main memory to draw it): %s.\n" % " ".join(RESIDENT)
    text += "; Their tiles start at FIRST; the faces' and charms' pictures are in their catalog records\n"
    text += "; (art/pictures, content/catalog)\n\n"
    text += "(import tables)\n\n(const ICON_BYTES u16 90)\n(const FIRST u8 %d)\n" % FIRST_TILE
    for i, n in enumerate(RESIDENT):
        text += "(const TILE_%s u8 %d)\n" % (n.upper(), FIRST_TILE + i)
    for i, n in enumerate(RESIDENT):
        data = H.icon_pixels(n)
        text += "(tables.packed_bytes icon_%d (\n%s) :in aux)\n" % (i, numbers(data))
    text += "(const PICTURES (array (ptr u8) %d)\n    (make (array (ptr u8) %d)\n%s)\n    :in aux)\n" % (
        len(RESIDENT), len(RESIDENT),
        "\n".join("        (addr_of (at icon_%d 0))" % i for i in range(len(RESIDENT))))
    return text


def pictures_module():
    # every face's and charm's card picture by name (icons.py, charm_icons.py), as the bytes the
    # catalog lays into its record on disk 2 (content/catalog): 15 rows of 6 bytes, two pixels a
    # byte. A macro, so no picture takes memory: only the records on the disk hold them
    import charm_icons
    pics = {}
    for n in icons.ICONS:
        if n not in ("nap", "door", "grabbed"):
            pics[n] = game_hud.icon_pixels(n)
    for n, rows in charm_icons.CHARMS.items():
        assert len(rows) == icons.ICON_H and all(len(r) == icons.ICON_W for r in rows), n
        if n in pics:
            raise SystemExit("game.py: the charm picture %s has a face picture's name" % n)
        pics[n] = game_hud.icon_pixels(n, rows)
    text = HEAD + "; the faces' and charms' card pictures by name (tools/dhgr/icons.py, charm_icons.py): 15 rows\n"
    text += "; of 11 pixels as nibbles, 6 bytes a row. Only content/catalog reads them, to lay each into its\n"
    text += "; record on disk 2: no picture takes memory\n\n"
    text += "(macro picture (name)\n    (match name\n"
    for n, data in pics.items():
        text += "        ('%s (list\n%s))\n" % (n, numbers(data))
    text += '        (_ (error "no card picture " name ": draw it in tools/dhgr/icons.py (a face) or "\n'
    text += '            "charm_icons.py (a charm), then python3 tools/dhgr/game.py"))))\n'
    return text


def font40_module():
    data = game_hud.font40()
    return HEAD + "; the 40-column font: 95 glyphs from ' ', 8 rows of (aux, main) bytes\n\n" + table("FONT40", "u8", data)


def all_screens():
    fights = screens.fights()
    return fights, [screen_of(F) for F in fights]


def main():
    os.makedirs(OUT, exist_ok=True)
    fights, fight_screens = all_screens()
    title_S = title_screen()
    sizes = table_sizes(fight_screens + [title_S])
    print(write("sprites.tsp", sprites_module(sizes, title_S)))
    print(write("hero.tsp", hero_module(sizes)))
    for F, S in zip(fights, fight_screens):
        print(write("screen_fight%d.tsp" % F["n"], fight_module(F, S, sizes)))
    print(write("screen_title.tsp", title_module(title_S, sizes)))
    print(write("hud_data.tsp", hud_module()))
    print(write("icons.tsp", icons_module()))
    print(write("pictures.tsp", pictures_module()))
    print(write("font40.tsp", font40_module()))


if __name__ == "__main__":
    main()
