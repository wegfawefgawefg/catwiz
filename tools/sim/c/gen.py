"""Writes the C sim's content (gen_content.h) from the proposal's tables, read by the Python
sim's own reader (content.py, tsp.py), so every number stays in tools/sim/proposal.

    python3 tools/sim/c/gen.py > tools/sim/c/gen_content.h     (the Makefile does this)
    python3 tools/sim/c/gen.py DIR > ...      the tables in DIR instead (make TABLES_DIR=DIR)

The header has the enums (effect kinds, combos, slots, aims, charm kinds) as E_hit, C_sweep,
S_wand, A_foe, K_mother, and the tables as static arrays: items, moves, enemy kinds, fights
(their enemies, cards, charms, nap, other door), charms, the starting items and the constants.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

import content  # noqa: E402
import tsp  # noqa: E402


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def enum(out, name, prefix, members):
    out.append("enum %s {" % name)
    for m in members:
        out.append("    %s%s," % (prefix, m))
    out.append("    %sCOUNT" % prefix)
    out.append("};")
    out.append("static const char *const %s_NAME[] = {%s};" % (
        name.upper(), ", ".join(cstr(m) for m in members)))


def main():
    if len(sys.argv) > 1:
        content.DIRS["proposal"] = [os.path.abspath(sys.argv[1])]
    dirs = content.DIRS["proposal"] + [os.path.join(content.GAME, "content")]
    R = content.load("proposal")
    c = tsp.Content(dirs + [content.GAME])
    effects = c.module("content/action").enums["Effect"]
    items_mod = c.module("content/items")
    slots = items_mod.enums["Slot"]
    combos = items_mod.enums["Combo"]
    aims = c.module("state").enums["Aim"]
    charm_kinds = c.module("content/encounters").enums["CharmKind"]
    zones = c.module("content/encounters").enums["Zone"]

    out = ["/* generated by gen.py from tools/sim/proposal: do not edit */",
           "#ifndef GEN_CONTENT_H", "#define GEN_CONTENT_H", ""]
    enum(out, "Effect", "E_", effects)
    enum(out, "Combo", "C_", combos)
    enum(out, "Slot", "S_", slots)
    enum(out, "Aim", "A_", aims)
    enum(out, "CharmKind", "K_", charm_kinds)
    enum(out, "Zone", "Z_", zones)
    out.append("")

    consts = [
        ("ITEM_COUNT", len(R.faces)),
        ("MOVE_COUNT", len(R.moves)),
        ("KIND_COUNT", len(R.kinds)),
        ("FIGHT_ROWS", len(R.fights)),
        ("FIGHT_COUNT", R.fight_count),
        ("CHARM_COUNT", len(R.charm_table)),
        ("HERO_HP", R.hero_hp),
        ("NAP_HEAL_SHIFT", R.rest_heal if R.rest_heal is not None else 0),
        ("ITEM_MOST", R.item_most),
        ("MOST_MANA", R.most_mana),
        ("FLEA_TURNS", R.fx["FLEA_TURNS"]),
        ("ZOOMIES_HITS", R.fx["ZOOMIES_HITS"]),
        ("SCREAM_SELF", R.fx["SCREAM_SELF"]),
        ("KITTEN_HIT", R.fx.get("KITTEN_HIT", 1)),
        ("KITTENS_MOST", R.fx.get("KITTENS_MOST", 5)),
        ("BADMILK_FLEAS", R.fx.get("BADMILK_FLEAS", 0)),
        ("REROLLS", R.rerolls),
        ("HAND", R.hand),
        ("HAIRBALL", R.junk_row),
        ("UP_CARD", 128),
    ]
    for name, v in consts:
        out.append("#define %s %d" % (name, v))
    out.append("")

    out.append("typedef struct { const char *name, *text; unsigned char slot, effect, amount,"
               " step, cost, combo, combo_n, aim; } ItemRow;")
    out.append("static const ItemRow ITEMS[ITEM_COUNT] = {")
    for f in R.faces:
        out.append("    {%s, %s, S_%s, E_%s, %d, %d, %d, C_%s, %d, A_%s}," % (
            cstr(f.name), cstr(f.text), f.slot, f.effect, f.amount, f.step, f.cost,
            f.combo, f.combo_n, f.aim))
    out.append("};")

    out.append("typedef struct { const char *text; unsigned char effect, amount, aim; } MoveRow;")
    out.append("static const MoveRow MOVES[MOVE_COUNT] = {")
    for m in R.moves:
        out.append("    {%s, E_%s, %d, A_%s}," % (cstr(m.text), m.effect, m.amount, m.aim))
    out.append("};")

    out.append("typedef struct { const char *name; unsigned char hp, ward, first, count, calls,"
               " then, stall; } KindRow;")
    out.append("static const KindRow KINDS[KIND_COUNT] = {")
    for k in R.kinds:
        out.append("    {%s, %d, %d, %d, %d, %d, %d, %d}," % (
            cstr(k.name), k.hp, k.ward, k.first, k.count, k.calls, k.then, k.stall))
    out.append("};")

    out.append("typedef struct { unsigned char zone, count, enemies[3], nap, charm, other; } FightRow;")
    out.append("static const FightRow FIGHTS[FIGHT_ROWS] = {")
    for f in R.fights:
        en = (f.enemies + [255, 255, 255])[:3]
        out.append("    {Z_%s, %d, {%s}, %d, %d, %d}," % (
            f.zone, len(f.enemies), ", ".join(map(str, en)), 1 if f.nap else 0,
            1 if f.charm else 0, f.other))
    out.append("};")
    # the reward pools: a card or charm, its weight, the fights won before it can come
    out.append("typedef struct { unsigned char what, weight, from; } OfferRow;")
    out.append("#define OFFER_COUNT %d" % len(R.offers))  # OFFER_CARDS
    out.append("static const OfferRow OFFERS[OFFER_COUNT] = {%s};" % ", ".join(
        "{%d, %d, %d}" % o for o in R.offers))
    out.append("#define CHARM_OFFER_COUNT %d" % len(R.charm_offers))
    out.append("static const OfferRow CHARM_OFFERS[CHARM_OFFER_COUNT] = {%s};" % ", ".join(
        "{%d, %d, %d}" % o for o in R.charm_offers))

    out.append("typedef struct { const char *name, *text; unsigned char kind, amount; } CharmRow;")
    out.append("static const CharmRow CHARMS[CHARM_COUNT] = {")
    for ch in R.charm_table:
        out.append("    {%s, %s, K_%s, %d}," % (cstr(ch["name"]), cstr(ch["text"]), ch["kind"],
                                               ch["amount"]))
    out.append("};")
    out.append("static const unsigned char STARTING_ITEMS[6] = {%s};" % (
        ", ".join(map(str, R.start_items))))
    out.append("")
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
